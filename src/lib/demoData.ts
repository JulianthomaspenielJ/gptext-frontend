// Calculate consistent statistics across modules
export const getConsistentStats = () => {
  const orders = getDemoOrders();
  const looms = getDemoLooms();
  const weavers = getDemoWeavers();
  const loomStatus = getDemoLoomStatus();

  // Order statistics
  const totalOrders = orders.length;
  const inProgress = orders.filter((o) => o.status === "In Progress").length;
  const planning = orders.filter((o) => o.status === "Planning").length;
  const completed = orders.filter((o) => o.status === "Completed").length;
  const onHold = orders.filter((o) => o.status === "On Hold").length;

  // Loom statistics
  const totalLooms = looms.length;
  const runningLooms = loomStatus.filter((s) => s.status === "running").length;
  const idleLooms = loomStatus.filter((s) => s.status === "idle").length;
  const maintenanceLooms = loomStatus.filter(
    (s) => s.status === "maintenance",
  ).length;
  const delayedLooms = loomStatus.filter((s) => s.status === "delayed").length;

  // Weaver statistics
  const totalWeavers = weavers.length;
  const activeWeavers = weavers.filter((w) => w.status === "Active").length;

  // Production statistics
  const totalMetersTarget = loomStatus.reduce(
    (sum, s) => sum + s.targetProduction,
    0,
  );
  const totalMetersActual = loomStatus.reduce(
    (sum, s) => sum + s.actualProduction,
    0,
  );
  const overallEfficiency =
    totalMetersTarget > 0
      ? Math.round((totalMetersActual / totalMetersTarget) * 100)
      : 0;

  return {
    orders: {
      total: totalOrders,
      inProgress,
      planning,
      completed,
      onHold,
    },
    looms: {
      total: totalLooms,
      running: runningLooms,
      idle: idleLooms,
      maintenance: maintenanceLooms,
      delayed: delayedLooms,
    },
    weavers: {
      total: totalWeavers,
      active: activeWeavers,
    },
    production: {
      targetMeters: totalMetersTarget,
      actualMeters: totalMetersActual,
      efficiency: overallEfficiency,
    },
  };
};
